import { ChromeController } from "./cdp_helper.mjs";
import { writeFileSync } from "node:fs";
const c = new ChromeController();
await c.start({ headless: true });
await c.newPage();
const dir = process.argv[2];
await c.setViewport({ width: 390, height: 844, mobile: true });
await c.navigate("https://chungdoi.com/vi/mau-thiep/minimalism-do-dam/demo", 3000);
await c.eval(`(() => { const b=[...document.querySelectorAll('button,a')].find(x=>/mở thiệp/i.test(x.innerText||'')); if(b) b.click(); })()`);
await new Promise(r=>setTimeout(r,4000));
const html = await c.eval(`(() => { const s=[...document.querySelectorAll('section')].find(x=>String(x.className).includes('w-[88%]')); return s? s.outerHTML : 'none'; })()`);
writeFileSync(dir+"/real_section.html", html);
console.log(html.length);
await c.eval(`window.scrollTo(0, 680)`); await new Promise(r=>setTimeout(r,1500));
await c.screenshot(dir+"/real_open_390.png");
await c.navigate("http://localhost:5173/demo?template=minimalism-do-dam", 3000);
await c.eval(`(() => { const b=[...document.querySelectorAll('button,a')].find(x=>/mở thiệp/i.test(x.innerText||'')); if(b) b.click(); })()`);
await new Promise(r=>setTimeout(r,4000));
await c.eval(`window.scrollTo(0, 680)`); await new Promise(r=>setTimeout(r,1500));
await c.screenshot(dir+"/clone_open_390.png");
process.exit(0);
